"""
Вывод скриптов, который не падает на консоли Windows.

Зачем: консоль Windows по умолчанию живёт в однобайтовой кодировке
(cp1251, а на свежей Windows — cp1252), и русский текст в сообщении об
ошибке превращается в UnicodeEncodeError. Скрипт, который должен был
сказать «ошибка в таком-то файле», вместо этого падает с трассировкой
про кодировку, и понять исходную проблему невозможно.

В CI вывод перенаправлен в файл, поэтому там кодировка вообще не
участвует — падает всё равно. Один перехват в начале main() решает
это везде.
"""
from __future__ import annotations

import sys


def use_utf8():
    """Перевести stdout и stderr в UTF-8, заменив непечатаемое на «?».

    Перекодировка самих символов не нужна: консоль Windows принимает
    байты как UTF-8, а в логе CI нужен именно UTF-8, иначе вместо
    русского текста будут знаки вопроса.
    """
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
